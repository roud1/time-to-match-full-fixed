#!/usr/bin/env node
/**
 * Builds the point clouds of the home-page particle animation
 * (client/components/home/particles-data.ts) from:
 *   - design/home-animation-reference.gif — the frame with the two faces facing each other
 *     (the scene itself moves them together, so the kiss is one smooth motion);
 *   - public/kairo/kairo-logo.webp — the heart-hourglass mark (left part of the logo).
 * Each set has N points: x, y in [-1, 1] (square canvas, centre 0) and brightness 0-255.
 * Stored as 3 bytes per point (see encode).
 * Run: node scripts/build-home-particles.mjs
 */
import sharp from "sharp"
import fs from "node:fs"
import path from "node:path"

const N = 6000
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..")
const GIF = path.join(ROOT, "design/home-animation-reference.gif")
const LOGO = path.join(ROOT, "public/kairo/kairo-logo.webp")

// Deterministic random numbers (same output on every run).
let seed = 20261128
const rnd = () => ((seed = (seed * 1664525 + 1013904223) >>> 0) / 4294967296)

async function frame(page) {
  const { data, info } = await sharp(GIF, { page }).raw().toBuffer({ resolveWithObject: true })
  return { data, w: info.width, h: info.height, c: info.channels }
}

/**
 * Weighted sample of N points. The luminance is smoothed first (isolated sparks of the GIF fade
 * out), and edges get extra weight, so the profiles read clearly as lines plus soft volume.
 */
function sample({ data, w, h, c }, { threshold, power, edge = 0, gamma = 1, keep, box, bright = (v) => (v - 70) * 1.35 }) {
  const lum = new Float32Array(w * h)
  for (let i = 0; i < w * h; i++) {
    const alpha = c === 4 ? data[i * c + 3] / 255 : 1
    const raw = (0.3 * data[i * c] + 0.55 * data[i * c + 1] + 0.15 * data[i * c + 2]) * alpha
    // Gamma lift: the faces in the reference are dark; this brings out their volume and edges.
    lum[i] = Math.pow(raw / 255, gamma) * 255
  }
  const blur = new Float32Array(w * h)
  for (let y = 1; y < h - 1; y++) {
    for (let x = 1; x < w - 1; x++) {
      let sum = 0
      for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) sum += lum[(y + dy) * w + x + dx]
      blur[y * w + x] = sum / 9
    }
  }
  const cand = []
  let total = 0
  for (let y = 1; y < h - 1; y++) {
    for (let x = 1; x < w - 1; x++) {
      const v = blur[y * w + x]
      if (v < threshold) continue
      if (keep && !keep(x / w, y / h)) continue
      const gx = blur[y * w + x + 1] - blur[y * w + x - 1]
      const gy = blur[(y + 1) * w + x] - blur[(y - 1) * w + x]
      const weight = Math.pow(v / 255, power) + (edge * Math.min(255, Math.abs(gx) + Math.abs(gy))) / 255
      total += weight
      cand.push([x, y, v, total])
    }
  }
  const out = []
  for (let k = 0; k < N; k++) {
    const r = rnd() * total
    let lo = 0
    let hi = cand.length - 1
    while (lo < hi) {
      const mid = (lo + hi) >> 1
      if (cand[mid][3] < r) lo = mid + 1
      else hi = mid
    }
    const [x, y, l] = cand[lo]
    const jx = x + rnd() - 0.5
    const jy = y + rnd() - 0.5
    const [bx, by, bw, bh] = box(w, h)
    out.push([((jx - bx) / bw) * 2 - 1, ((jy - by) / bh) * 2 - 1, Math.min(255, Math.max(0, Math.round(bright(l))))])
  }
  return out
}

/** The two glowing arcs of the reference are drawn as vectors; keep them out of the face clouds. */
const notArc = (fx, fy) => {
  const r = Math.hypot(fx - 0.5, fy - 0.5)
  const top = fy < 0.32 && fx > 0.45
  const bottom = fy > 0.68 && fx < 0.55
  return !(r > 0.36 && (top || bottom))
}

const square = (w, h) => [0, 0, w, h]
const faces = { threshold: 75, power: 2, edge: 1, gamma: 0.45, keep: notArc, box: square, bright: (v) => (v - 50) * 1.6 }
const apart = sample(await frame(8), faces)

// Logo mark: the left ~31.5 % of the logo image (heart + hourglass), centred in its own square.
const meta = await sharp(LOGO).metadata()
const markW = Math.round(meta.width * 0.315)
const mark = await sharp(LOGO).extract({ left: 0, top: 0, width: markW, height: meta.height }).raw().toBuffer({ resolveWithObject: true })
const markFrame = { data: mark.data, w: mark.info.width, h: mark.info.height, c: mark.info.channels }
const side = Math.max(markFrame.w, markFrame.h)
const logo = sample(markFrame, {
  threshold: 60,
  power: 1.2,
  edge: 0.5,
  box: (w, h) => [(w - side) / 2, (h - side) / 2, side, side],
})

/** 3 bytes per point: x, y (0-255 over [-1, 1]) and brightness — compact; resolution ~1 px. */
function encode(points) {
  const buf = Buffer.alloc(points.length * 3)
  const q = (v) => Math.round(((Math.max(-1, Math.min(1, v)) + 1) / 2) * 255)
  points.forEach(([x, y, b], i) => {
    buf[i * 3] = q(x)
    buf[i * 3 + 1] = q(y)
    buf[i * 3 + 2] = b
  })
  return buf.toString("base64")
}

const out = `/* Generated by scripts/build-home-particles.mjs — do not edit by hand. */
/** Points per set; each point is 3 bytes: x, y (0-255 over [-1, 1]) and brightness 0-255. */
export const PARTICLE_COUNT = ${N}
export const FACES_APART = "${encode(apart)}"
export const KAIRO_MARK = "${encode(logo)}"
`
fs.writeFileSync(path.join(ROOT, "client/components/home/particles-data.ts"), out)
console.log("particles-data.ts", (out.length / 1024).toFixed(1), "KB")
