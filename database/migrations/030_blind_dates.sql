-- Luvia Blind Date (Phase 1): queue, rooms, messages, game sessions, connection reports, AI usage.
-- Additive only: new tables, indexes and one nullable column. Safe to apply on a live database.
-- Everything referencing users uses ON DELETE CASCADE, so account deletion (GDPR) removes it.

-- Waiting users. One row per user; matched or expired rows are deleted.
CREATE TABLE IF NOT EXISTS blind_date_queue (
  user_id UUID PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
  lang TEXT NOT NULL DEFAULT 'en',
  languages TEXT[] NOT NULL DEFAULT '{}',
  joined_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- Refreshed by the client's polling; stale rows are ignored and cleaned up.
  last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS blind_date_queue_seen_idx ON blind_date_queue (last_seen_at);

-- A private 10-minute room for two people.
CREATE TABLE IF NOT EXISTS blind_date_rooms (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_a UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  user_b UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'active',
  started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  ends_at TIMESTAMPTZ NOT NULL,
  decide_until TIMESTAMPTZ NOT NULL,
  closed_at TIMESTAMPTZ,
  close_reason TEXT,
  closed_by UUID REFERENCES users (id) ON DELETE SET NULL,
  -- Mutual reveal: each person's consent to show their photo progressively.
  reveal_consent_a BOOLEAN NOT NULL DEFAULT false,
  reveal_consent_b BOOLEAN NOT NULL DEFAULT false,
  -- Highest reveal stage reached (0, 25, 50, 75, 100); never sent as a photo URL.
  reveal_level SMALLINT NOT NULL DEFAULT 0,
  decision_a TEXT,
  decision_b TEXT,
  match_id UUID REFERENCES matches (id) ON DELETE SET NULL,
  -- Matchmaking context kept for analytics (no personal data): common interest count, distance bucket.
  match_meta JSONB NOT NULL DEFAULT '{}'::jsonb,
  -- Incremented on every change; clients poll with ?since=<version>.
  version INTEGER NOT NULL DEFAULT 1,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT blind_date_rooms_distinct_users CHECK (user_a <> user_b),
  CONSTRAINT blind_date_rooms_status_chk CHECK (status IN ('active', 'deciding', 'closed')),
  CONSTRAINT blind_date_rooms_decision_a_chk CHECK (decision_a IS NULL OR decision_a IN ('continue', 'pass')),
  CONSTRAINT blind_date_rooms_decision_b_chk CHECK (decision_b IS NULL OR decision_b IN ('continue', 'pass')),
  CONSTRAINT blind_date_rooms_reveal_chk CHECK (reveal_level IN (0, 25, 50, 75, 100))
);

-- At most one open room per user (protects against double matchmaking).
CREATE UNIQUE INDEX IF NOT EXISTS blind_date_rooms_open_a_uniq
  ON blind_date_rooms (user_a) WHERE status <> 'closed';
CREATE UNIQUE INDEX IF NOT EXISTS blind_date_rooms_open_b_uniq
  ON blind_date_rooms (user_b) WHERE status <> 'closed';
CREATE INDEX IF NOT EXISTS blind_date_rooms_pair_idx ON blind_date_rooms (user_a, user_b, started_at DESC);
CREATE INDEX IF NOT EXISTS blind_date_rooms_b_idx ON blind_date_rooms (user_b, started_at DESC);
CREATE INDEX IF NOT EXISTS blind_date_rooms_open_idx ON blind_date_rooms (status, decide_until) WHERE status <> 'closed';

CREATE TABLE IF NOT EXISTS blind_date_messages (
  id BIGSERIAL PRIMARY KEY,
  room_id UUID NOT NULL REFERENCES blind_date_rooms (id) ON DELETE CASCADE,
  sender_id UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  body TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT blind_date_messages_body_len CHECK (char_length(body) BETWEEN 1 AND 1000)
);

CREATE INDEX IF NOT EXISTS blind_date_messages_room_idx ON blind_date_messages (room_id, id);

-- Mini-games and compatibility challenges (Phase 4). `state` holds the game-specific data;
-- answers of one player stay server-side until the game reveals them.
CREATE TABLE IF NOT EXISTS blind_date_game_sessions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  room_id UUID NOT NULL REFERENCES blind_date_rooms (id) ON DELETE CASCADE,
  game_key TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'active',
  started_by UUID REFERENCES users (id) ON DELETE SET NULL,
  state JSONB NOT NULL DEFAULT '{}'::jsonb,
  result JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  completed_at TIMESTAMPTZ,
  CONSTRAINT blind_date_game_status_chk CHECK (status IN ('active', 'completed', 'abandoned'))
);

CREATE INDEX IF NOT EXISTS blind_date_game_room_idx ON blind_date_game_sessions (room_id, created_at);
CREATE UNIQUE INDEX IF NOT EXISTS blind_date_game_one_active
  ON blind_date_game_sessions (room_id) WHERE status = 'active';

-- Connection Report per participant (Phase 5). Generated by AI (with consent) or locally.
CREATE TABLE IF NOT EXISTS blind_date_connection_reports (
  room_id UUID NOT NULL REFERENCES blind_date_rooms (id) ON DELETE CASCADE,
  user_id UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  source TEXT NOT NULL DEFAULT 'local',
  report JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (room_id, user_id),
  CONSTRAINT blind_date_report_source_chk CHECK (source IN ('local', 'ai'))
);

-- AI requests (cost and rate analytics; no prompt or message content stored).
CREATE TABLE IF NOT EXISTS ai_usage (
  id BIGSERIAL PRIMARY KEY,
  user_id UUID REFERENCES users (id) ON DELETE SET NULL,
  feature TEXT NOT NULL,
  provider TEXT NOT NULL,
  model TEXT,
  input_tokens INTEGER,
  output_tokens INTEGER,
  cost_usd NUMERIC(10, 6),
  cached BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ai_usage_created_idx ON ai_usage (created_at);
CREATE INDEX IF NOT EXISTS ai_usage_user_idx ON ai_usage (user_id, created_at);

-- Reports filed from a blind date room point to it (nullable, existing rows unaffected).
ALTER TABLE reports ADD COLUMN IF NOT EXISTS blind_date_room_id UUID REFERENCES blind_date_rooms (id) ON DELETE SET NULL;
